def case(id, category, subject, stem, rubric, answer, reference, expected,
         reason, replay_score, *, kind="计算题", steps=None, tool_fault=None,
         model_fault=None, verification=None, shared_group=None):
    return {
        "id": id, "category": category, "subject": subject,
        "label_kind": "synthetic_explicit_rule",
        "problem": {"q_id": id, "number": id, "type": kind, "stem": stem,
                    "criterion": rubric, "reference_answer": reference, "max_score": 10},
        "answer": answer,
        "expected": {"score_interval": expected, "rationale": reason,
                     "score_required": model_fault is None,
                     "forced_review_allowed": model_fault is not None},
        "replay": {
            "provenance": "authored_fixed_reply_not_a_model_measurement",
            "response": {"score": replay_score, "max_score": 10, "confidence": .95,
                         "comment": reason, "steps": [
                             {"step_no": n + 1, "desc": desc, "is_correct": ok, "score": pts}
                             for n, (desc, ok, pts) in enumerate(
                                 steps or [("按本题显式标准计分", True, replay_score)])]},
            "tool_fault": tool_fault, "model_fault": model_fault},
        "verification": verification, "shared_group": shared_group,
    }


def verify(student, reference, status, **kwargs):
    return {"request": {"student_expression": student, "reference_expression": reference, **kwargs},
            "allowed_statuses": status if isinstance(status, list) else [status]}


